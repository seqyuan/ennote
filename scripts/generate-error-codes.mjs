#!/usr/bin/env node
/**
 * Generate the inventory of error codes the Worker can emit.
 *
 * The codebase names error codes in three places — domain ErrorCode constants,
 * string literals passed to writeError in the API layer, and the contract's
 * free-form `ErrorEnvelope.error.code` — and nothing kept them in step. A full
 * unification is a refactor of 300+ call sites, so the first step is making the
 * vocabulary *visible*: this list is generated from the sources and CI fails when
 * it drifts, which turns "we added an error code" into a reviewable diff instead
 * of a silent change clients discover at runtime.
 *
 * Run: npm run generate:error-codes
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

// Resolved from the working directory like the other repository guards, so a
// fixture tree can be checked the same way CI checks this one.
const root = process.cwd();
const output = path.join(root, "contracts/error-codes.txt");
const check = process.argv.includes("--check");

const CODE_SHAPE = /^[a-z][a-z0-9_]*$/;

/** `writeError(w, r, http.StatusX, "code", ...)` in the Worker. */
const WRITE_ERROR = /write[A-Za-z]*Error\(\s*[^,]+,\s*[^,]+,\s*http\.[A-Za-z]+,\s*"([a-z0-9_]+)"/g;
/** `ErrorSomething ErrorCode = "code"` in domain. */
const DOMAIN_CODE = /Error[A-Za-z0-9]*\s+ErrorCode\s*=\s*"([a-z0-9_]+)"/g;
/** `domain.NewCodedError(domain.ErrorSomething, ...)` needs no scan: the values
 *  come from the domain constants above. */
/** Codes assigned into an error envelope outside the API layer's helper. */
const ENVELOPE_CODE = /"code":\s*"([a-z0-9_]+)"/g;

async function goSources(directory, found = []) {
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "testdata" || entry.name === "node_modules") continue;
      await goSources(full, found);
      continue;
    }
    if (!entry.name.endsWith(".go") || entry.name.endsWith("_test.go")) continue;
    found.push(full);
  }
  return found;
}

const files = await goSources(path.join(root, "ennoworker"));
const codes = new Set();
const malformed = [];

for (const file of files) {
  const contents = await readFile(file, "utf8");
  for (const pattern of [WRITE_ERROR, DOMAIN_CODE, ENVELOPE_CODE]) {
    for (const match of contents.matchAll(pattern)) {
      const code = match[1];
      if (!CODE_SHAPE.test(code)) {
        malformed.push(`${path.relative(root, file)}: ${code}`);
        continue;
      }
      codes.add(code);
    }
  }
}

if (malformed.length > 0) {
  console.error(`Error codes must be lowercase snake_case:\n  ${malformed.join("\n  ")}`);
  process.exit(1);
}

const sorted = [...codes].sort();
const body = [
  "# Error codes the Worker can emit.",
  "#",
  "# Generated by scripts/generate-error-codes.mjs from writeError call sites, domain",
  "# ErrorCode constants, and literal envelope codes. Do not edit by hand: run",
  "# `npm run generate:error-codes` and commit the diff, which makes a vocabulary",
  "# change visible in review instead of at runtime.",
  `# ${sorted.length} codes.`,
  ...sorted,
  "",
].join("\n");

const existing = await readFile(output, "utf8").catch(() => null);
if (check) {
  if (existing !== body) {
    console.error("contracts/error-codes.txt is out of date: run `npm run generate:error-codes`.");
    process.exit(1);
  }
  console.log(`Error-code inventory is current (${sorted.length} codes).`);
} else {
  await writeFile(output, body);
  console.log(`Wrote contracts/error-codes.txt (${sorted.length} codes).`);
}
