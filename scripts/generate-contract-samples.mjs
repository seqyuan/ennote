#!/usr/bin/env node
/**
 * Turn the Worker's captured answers into type assertions.
 *
 * `generate:api` proves the generated types match the contract, and the router
 * parity test proves the mux serves the declared operations. Nothing proved a
 * handler's JSON matches the type it promised, so a renamed or dropped field was
 * invisible until a client read `undefined` from it. This closes that gap with the
 * tools already in the repository: a Go test captures what the Worker actually
 * answers (ennoworker/internal/api/testdata/contract-samples), this script turns
 * each capture into a typed constant, and `tsc` decides whether they agree.
 *
 * What it checks, through TypeScript: required fields, field types, and — because
 * the constants are fresh object literals — properties the schema does not declare.
 * `openapi-typescript` emits no index signature for an object with a properties
 * list, so the excess-property check applies whether or not the schema says
 * additionalProperties: false.
 *
 * What it cannot check: format/pattern/minimum, cross-field rules, and anything
 * about status codes or headers. Those need a validator, not a type.
 *
 * Run: npm run generate:contract-samples
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

// Resolved from the working directory like the other repository guards, so a
// fixture tree can be checked the same way CI checks this one.
const root = process.cwd();
const samplesDirectory = path.join(root, "ennoworker/internal/api/testdata/contract-samples");
const output = path.join(root, "tests/contract-samples.gen.ts");
const check = process.argv.includes("--check");

/** `<operationId>-<status>.json`, as written by TestContractSamples. */
const SAMPLE_NAME = /^(?<operation>[A-Za-z][A-Za-z0-9]*)-(?<status>\d{3})\.json$/;

async function samples() {
  let entries;
  try {
    entries = await readdir(samplesDirectory);
  } catch {
    throw new Error(
      `${samplesDirectory} is missing; run ENNOTE_UPDATE_CONTRACT_SAMPLES=1 go test ./internal/api/ -run TestContractSamples`,
    );
  }
  const found = [];
  for (const entry of entries.sort()) {
    const match = SAMPLE_NAME.exec(entry);
    if (!match) {
      throw new Error(
        `${entry} is not <operationId>-<status>.json; the file name is the only thing that ties a sample to the operation it belongs to`,
      );
    }
    const body = await readFile(path.join(samplesDirectory, entry), "utf8");
    found.push({
      file: entry,
      operation: match.groups.operation,
      status: Number(match.groups.status),
      // Re-serialized rather than copied so the literal is normalised no matter
      // how it was hand-edited.
      literal: JSON.stringify(JSON.parse(body), null, 2),
    });
  }
  if (found.length === 0) {
    throw new Error(`no samples in ${samplesDirectory}; run ENNOTE_UPDATE_CONTRACT_SAMPLES=1 go test ./internal/api/ -run TestContractSamples`);
  }
  return found;
}

function render(found) {
  const header = `// Code generated by scripts/generate-contract-samples.mjs; DO NOT EDIT.
//
// Each constant is one stored answer from the Worker, annotated with the response
// type its operation declares in contracts/openapi.yaml. If a handler's JSON stops
// matching the contract, \`npm run typecheck\` fails here rather than in a client
// that reads undefined.
//
// Refresh a sample with:
//   ENNOTE_UPDATE_CONTRACT_SAMPLES=1 go test ./internal/api/ -run TestContractSamples
//   npm run generate:contract-samples
`;
  const body = found
    .map(({ operation, status, literal }) => {
      const constant = `${operation}${status}`;
      return `/** ${operation} answering ${status}. */
export const ${constant}: WorkerOperationResponse<"${operation}", ${status}> = ${literal};
`;
    })
    .join("\n");
  return `${header}
import type { WorkerOperationResponse } from "@/lib/contract-samples";

${body}`;
}

const found = await samples();
const rendered = render(found);

if (check) {
  let existing = "";
  try {
    existing = await readFile(output, "utf8");
  } catch {
    existing = "";
  }
  if (existing !== rendered) {
    console.error(
      "tests/contract-samples.gen.ts is out of date; run: npm run generate:contract-samples",
    );
    process.exit(1);
  }
  console.log(`Contract samples are current (${found.length} samples).`);
} else {
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, rendered);
  console.log(`Wrote tests/contract-samples.gen.ts (${found.length} samples).`);
}
